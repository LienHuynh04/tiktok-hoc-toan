type Suit = keyof typeof SUITS;
const RANKS: [string, string][] = [
  ['Át', 'Ace'], ['Hai', 'Two'], ['Ba', 'Three'], ['Bốn', 'Four'], ['Năm', 'Five'],
  ['Sáu', 'Six'], ['Bảy', 'Seven'], ['Tám', 'Eight'], ['Chín', 'Nine'], ['Mười', 'Ten'],
  ['Tiểu Đồng', 'Page'], ['Hiệp Sĩ', 'Knight'], ['Nữ Hoàng', 'Queen'], ['Vua', 'King'],
];
const S = (suit: Suit, r: number, keywords: string, up: string, rev: string, tipUp: string, tipRev: string): Card78 => ({
  id: `${suit}-${String(r).padStart(2, '0')}`,
  img: `/assets/cards/${suit}-${String(r).padStart(2, '0')}.jpg`,
  name: `${RANKS[r - 1][0]} ${SUITS[suit].vn}`,
  en: `${RANKS[r - 1][1]} of ${SUITS[suit].en}`,
  keywords, up, rev, tipUp, tipRev,
});

